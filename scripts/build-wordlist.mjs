#!/usr/bin/env node
/**
 * Regenerates src/lib/wordlist.ts — the bundled passphrase word list.
 *
 * Provenance
 * ----------
 * Source: the Hunspell en_US dictionary (en_US.dic), which is generated from
 * SCOWL (Spell Checker Oriented Word Lists) by Kevin Atkinson.
 * SCOWL licence: permissive (use, copy, modify, distribute, sell) with notice —
 * see docs/WORDLIST.md for the full notice.
 *
 * Selection (deterministic, reproducible):
 *  1. Keep entries that are lowercase a–z only, 4–7 letters (no proper nouns,
 *     no apostrophes, no accents).
 *  2. Keep only root words that carry at least one affix flag. Words with more
 *     derivable forms tend to be more common, which makes passphrases easier
 *     to remember.
 *  3. Drop words matching a profanity / slur blocklist.
 *  4. Rank by number of affix flags (desc). Within a tie, order by SHA-256 of
 *     the word so the cut-off does not favour any letter of the alphabet.
 *  5. Take exactly 7,776 (= 6^5) words → log2(7776) ≈ 12.925 bits per word.
 *
 * Usage: node scripts/build-wordlist.mjs /usr/share/hunspell/en_US.dic
 */
import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';

const SIZE = 7776;
const src = process.argv[2] ?? '/usr/share/hunspell/en_US.dic';
const out = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../src/lib/wordlist.ts');

// Substring blocklist (kept short and broad; false positives only shrink the pool).
const BLOCK = [
  'fuck', 'shit', 'cunt', 'cock', 'dick', 'piss', 'slut', 'whore', 'bitch', 'bastard', 'damn',
  'nigg', 'negro', 'fag', 'dyke', 'tranny', 'retard', 'spic', 'kike', 'chink', 'gook', 'wetback',
  'rape', 'porn', 'anal', 'anus', 'penis', 'vagina', 'boob', 'tits', 'titty', 'nazi', 'kill',
  'murder', 'suicid', 'corpse', 'gore', 'semen', 'sperm', 'orgasm', 'horny', 'sexy', 'sex',
  'pubic', 'crap', 'arse', 'turd', 'twat', 'wank', 'prick', 'pussy', 'butt', 'homo', 'lesb',
  'gay', 'jew', 'muslim', 'islam', 'christ', 'hindu', 'hitler', 'slave', 'pimp', 'hooker',
  'incest', 'molest', 'pedo', 'dildo', 'bong', 'heroin', 'cocaine', 'opium', 'drug', 'torture',
  'abort', 'cancer', 'tumor', 'nude', 'naked', 'strip', 'bomb', 'gun', 'rifle', 'pistol', 'stab',
];

const lines = fs.readFileSync(src, 'utf8').split('\n').slice(1);
const seen = new Set();
const cands = [];
for (const line of lines) {
  const [word, flags = ''] = line.trim().split('/');
  if (!/^[a-z]{4,7}$/.test(word) || !flags || seen.has(word)) continue;
  if (BLOCK.some((b) => word.includes(b))) continue;
  seen.add(word);
  const h = crypto.createHash('sha256').update(word).digest('hex');
  cands.push({ word, n: flags.length, h });
}
cands.sort((a, b) => b.n - a.n || (a.h < b.h ? -1 : a.h > b.h ? 1 : 0));
if (cands.length < SIZE) throw new Error(`Only ${cands.length} candidates`);
const words = cands.slice(0, SIZE).map((c) => c.word).sort();
const digest = crypto.createHash('sha256').update(words.join('\n')).digest('hex');

const body = `// AUTO-GENERATED by scripts/build-wordlist.mjs — do not edit by hand.
// Source: Hunspell en_US dictionary derived from SCOWL (© Kevin Atkinson, permissive licence).
// See docs/WORDLIST.md for provenance and licence. ${SIZE} words, SHA-256 of newline-joined list:
// ${digest}
const RAW =
  ${JSON.stringify(words.join(' '))};

export const WORDLIST: readonly string[] = Object.freeze(RAW.split(' '));
export const WORDLIST_SHA256 = '${digest}';
`;
fs.writeFileSync(out, body);
console.log(`Wrote ${words.length} words to ${path.relative(process.cwd(), out)} (sha256 ${digest.slice(0, 16)}…)`);
